/**
 * Evaluation harness. Four separate measures, each k of n over a
 * human-reviewable fixture set. Prints a report and writes
 * docs/EVALUATION-RESULTS.md. Fails (exit 1) only if the harness itself
 * cannot run; a low score is reported, not hidden.
 */

import { writeFileSync } from "node:fs";
import { evaluate } from "@/engine/evaluate";
import { ENGINE_VERSION } from "@/engine/types";
import { extractRules } from "@/extraction";
import { DEMO_CLAUSES, DEMO_FIXTURE_VERSION } from "@/fixtures/demo-policy";
import { retrieveClauses } from "@/retrieval";
import { CALCULATION_CASES, EXTRACTION_FIELDS, FIXTURE_REVIEW, REFUSAL_CASES, RETRIEVAL_CASES } from "../tests/eval/fixtures";

interface Measure {
  name: string;
  passed: number;
  total: number;
  dataset: string;
  failures: string[];
}

function same(a: unknown, b: unknown): boolean {
  return JSON.stringify(a) === JSON.stringify(b);
}

function retrieval(): Measure {
  const failures: string[] = [];
  for (const c of RETRIEVAL_CASES) {
    const top = retrieveClauses(c.question, DEMO_CLAUSES, 1)[0]?.clauseId ?? "(none)";
    if (top !== c.expected) failures.push(`"${c.question}" → got ${top}, expected ${c.expected}`);
  }
  return { name: "Clause retrieval accuracy (top-1)", passed: RETRIEVAL_CASES.length - failures.length, total: RETRIEVAL_CASES.length, dataset: `${RETRIEVAL_CASES.length} questions over the synthetic wording (5 clauses)`, failures };
}

function extraction(): Measure {
  const extracted = extractRules(DEMO_CLAUSES);
  const failures: string[] = [];
  for (const f of EXTRACTION_FIELDS) {
    const actual = f.actual(extracted);
    if (!same(actual, f.expected)) failures.push(`${f.field}: got ${JSON.stringify(actual)}, expected ${JSON.stringify(f.expected)}`);
  }
  return { name: "Rule extraction accuracy (field-level)", passed: EXTRACTION_FIELDS.length - failures.length, total: EXTRACTION_FIELDS.length, dataset: `${EXTRACTION_FIELDS.length} rule fields of the synthetic wording, against the reviewed ruleset`, failures };
}

function calculation(): Measure {
  const failures: string[] = [];
  let fields = 0;
  let fieldFailures = 0;
  for (const c of CALCULATION_CASES) {
    const r = evaluate(c.inputs, c.scenario);
    const bad: string[] = [];
    for (const e of c.expect) {
      fields++;
      const actual = e.read(r);
      if (actual !== e.expected) {
        fieldFailures++;
        bad.push(`${e.field}: got ${String(actual)}, expected ${String(e.expected)}`);
      }
    }
    if (bad.length) failures.push(`${c.name}: ${bad.join("; ")}`);
  }
  return {
    name: "Calculation correctness (exact match in paise)",
    passed: CALCULATION_CASES.length - failures.length,
    total: CALCULATION_CASES.length,
    dataset: `${CALCULATION_CASES.length} scenarios, ${fields} expected amounts (${fields - fieldFailures} matched), hand-computed from docs/PRD.md Appendix A`,
    failures,
  };
}

function refusal(): Measure {
  const failures: string[] = [];
  for (const c of REFUSAL_CASES) {
    const r = evaluate(c.inputs, c.scenario);
    const bad: string[] = [];
    if (r.overallState !== c.expectedOverall) bad.push(`overall ${r.overallState}, expected ${c.expectedOverall}`);
    for (const m of c.mustBeNull) {
      const v = m.read(r);
      if (v !== null && v !== undefined) bad.push(`${m.field} is ${JSON.stringify(v)}, expected no number`);
    }
    const codes = r.uncertainties.map((u) => u.code);
    for (const code of c.expectedCodes) if (!codes.includes(code)) bad.push(`missing uncertainty ${code}`);
    if (bad.length) failures.push(`${c.name}: ${bad.join("; ")}`);
  }
  return { name: "Uncertainty and refusal quality", passed: REFUSAL_CASES.length - failures.length, total: REFUSAL_CASES.length, dataset: `${REFUSAL_CASES.length} cases with an expected state, values that must stay unknown, and expected reasons`, failures };
}

const measures = [retrieval(), extraction(), calculation(), refusal()];

const lines: string[] = [
  "# Evaluation results",
  "",
  "Generated by `npm run eval`. Do not edit by hand; CI fails if this file is stale.",
  "",
  `Engine ${ENGINE_VERSION}, demo fixture ${DEMO_FIXTURE_VERSION}. Fixtures authored ${FIXTURE_REVIEW.authoredOn} by ${FIXTURE_REVIEW.authoredBy}. Human review: ${FIXTURE_REVIEW.humanReview}.`,
  "",
  "All four measures run on the **synthetic** demo wording only. No real insurer wording has been measured. These numbers say nothing about accuracy on real policies.",
  "",
  "| Measure | Result | Dataset |",
  "|---|---|---|",
  ...measures.map((m) => `| ${m.name} | **${m.passed} of ${m.total}** | ${m.dataset} |`),
  "",
];
const allFailures = measures.flatMap((m) => m.failures.map((f) => `- ${m.name}: ${f}`));
lines.push("## Failures", "", ...(allFailures.length ? allFailures : ["None."]), "");

const report = lines.join("\n");
writeFileSync("docs/EVALUATION-RESULTS.md", report);
console.log(report);
